"""Evidence-backed sales stage rules shared by extraction and CRM delivery."""

import re

from .models import Project


STAGE_PATTERNS = {
    "new": r"\b(?:создали|открыли|поступила)\s+(?:новую\s+)?сделк\w*\b",
    "in_work": r"\b(?:(?:взяли|приняли)\s+в\s+работу|начали\s+работать|приступили\s+к\s+работе)\b",
    "visit_scheduled": r"\b(?:назначили|согласовали|запланировали|договорились\s+о)\s+(?:выезд|обследовани\w*|встреч\w*\s+на\s+объект\w*)\b",
    "visit_completed": r"\b(?:выезд\s+(?:состоялся|провели|совершили|выполнен)|провели\s+обследовани\w*\s+на\s+объект\w*|были\s+на\s+объект\w*)\b",
    "project_received": r"\b(?:получили\s+(?:проект\w*|проектн\w*\s+документац\w*|чертеж\w*)|(?:проект\w*|проектн\w*\s+документац\w*|чертеж\w*)\s+получен[аыо]?|нам\s+(?:прислали|передали|направили)\s+(?:проект\w*|проектн\w*\s+документац\w*|чертеж\w*)|проектн\w*\s+документац\w*\s+получили)\b",
    "calculation": r"\b(?:начали|делаем|ведём|ведем|выполняем|подготовили)\s+(?:расч[её]т|просч[её]т|подбор)\b|\b(?:рассчитываем|просчитываем)\b",
    "proposal_sent": r"\b(?:отправили|направили|выслали|передали|предоставили)\s+(?:кп|коммерческ\w*\s+предложени\w*)\s+(?:клиенту|заказчику)\b|\b(?:кп|коммерческ\w*\s+предложени\w*)\s+(?:отправлено|направлено|передано|предоставлено)\s+(?:клиенту|заказчику)\b|\b(?:кп|коммерческ\w*\s+предложени\w*)\s+отправили\s+(?:клиенту|заказчику)\b",
    "contract": r"\b(?:договор|контракт)\s+(?:подписан|заключ[её]н)|\bподписали\s+(?:договор|контракт)\b|\b(?:отправили|направили|передали)\s+(?:договор|контракт)\s+(?:клиенту|заказчику)\s+на\s+подписани\w*\b",
    "invoicing": r"\b(?:выставили|выставлен[аыо]?)\s+(?:сч[её]т|счета)\s+(?:клиенту|заказчику)|\b(?:клиент|заказчик)\w*\s+(?:оплатил|оплатили|произв[её]л\w*\s+оплату)|\bполучили\s+оплату\s+от\s+(?:клиент\w*|заказчик\w*)",
}


def sales_stage_rank(stage):
    return next((index for index, (value, _) in enumerate(Project.SALES_STAGE_CHOICES)
                 if value == stage), -1)


def stage_has_evidence(stage, text):
    """Require an explicit completed/current event; planned or negated text is insufficient."""
    pattern = STAGE_PATTERNS.get(stage)
    if not pattern or not isinstance(text, str):
        return False
    if re.search(r"\b(?:не\s+(?:назначили|согласовали|получили|получен|отправили|направили|передали|подписан|оплатил)|пока\s+не|ещ[её]\s+не|планируем|планируется|надо\s+(?:отправить|подписать|выставить)|нужно\s+(?:отправить|подписать|выставить))\b", text, re.I):
        return False
    return bool(re.search(pattern, text, re.I))
